export type MagazineErrorCode =
  (typeof MAGAZINE_ERROR_CODE)[keyof typeof MAGAZINE_ERROR_CODE];

/**
 * Separates a code from its English sentence inside a class-validator
 * constraint message. `MagazineValidationCodeInterceptor` splits on it.
 */
export const VALIDATION_CODE_SEPARATOR = ': ';

/**
 * A class-validator `message` that carries a magazine code. The global
 * `ValidationPipe` keeps only the message strings of a failed DTO, so the code
 * travels at the front of the string, followed by the exact English sentence
 * class-validator would have written by default (`$property` and
 * `$constraint1` are still substituted by class-validator).
 * `MagazineValidationCodeInterceptor` moves the code into the body's `code` and
 * `codes` fields and restores the plain sentence in `message`.
 */
export function codedValidationMessage(
  code: MagazineErrorCode,
  sentence: string,
): string {
  return `${code}${VALIDATION_CODE_SEPARATOR}${sentence}`;
}

/** `@IsString()`'s default sentence, coded `MAGAZINE_FIELD_NOT_TEXT`. */
export const NOT_TEXT_VALIDATION_MESSAGE = codedValidationMessage(
  MAGAZINE_ERROR_CODE.MAGAZINE_FIELD_NOT_TEXT,
  '$property must be a string',
);

/** `@MinLength()`'s default sentence, coded. */
export function tooShortValidationMessage(code: MagazineErrorCode): string {
  return codedValidationMessage(
    code,
    '$property must be longer than or equal to $constraint1 characters',
  );
}

/** `@MaxLength()`'s default sentence, coded. */
export function tooLongValidationMessage(code: MagazineErrorCode): string {
  return codedValidationMessage(
    code,
    '$property must be shorter than or equal to $constraint1 characters',
  );
}
